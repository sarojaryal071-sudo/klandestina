// rawGallery.albums[].title is {en, fi} (straight from data/gallery.json,
// written by scripts/build-gallery.mjs) — every gallery component only
// ever deals in plain, already-in-the-right-language strings, same as
// every other component on the site, so this is the one place that
// picks a language out of it.
function resolveGallery() {
  return {
    total: rawGallery.total,
    albums: rawGallery.albums.map((a) => ({ ...a, title: pickLang(a.title) })),
  };
}

// Bundles every gallery-related i18n string/template into one object so
// script.js stays the only place that calls t() — galleryMosaic.js/
// galleryOverlay.js/galleryPhotoViewer.js just read plain strings or call
// the small closures below, the same "components don't know about i18n"
// split every other component already follows (see dishCarousel.js's
// {prev, next} labels for the established pattern). The three *Fn
// closures exist because those strings need fresh numbers substituted in
// on every photo/navigation change, not just once at render time.
function buildGalleryLabels() {
  return {
    heading: t("gallery.heading"),
    close: t("gallery.close"),
    closeGallery: t("gallery.closeGallery"),
    previous: t("gallery.previous"),
    next: t("gallery.next"),
    all: t("gallery.all"),
    seeAllPhotosFn: (count) => t("gallery.seeAllPhotos", { count }),
    counterFn: (current, total) => t("gallery.photoCounter", { current, total }),
    ofTotalFn: (current, total) => t("gallery.photoOfTotal", { current, total }),
    altPhotoFn: (album, n) => t("gallery.altPhoto", { album, n }),
  };
}

