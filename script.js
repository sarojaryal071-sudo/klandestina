// Resolves data/events.json's upcoming/ongoing occurrences (see
// eventsLogic.js), picks each one's title/description/tag/price to the
// active language the same way menu items and dishes already do, and
// either renders the section or hides it + its nav links entirely when
// nothing qualifies — same "hide rather than show empty" rule Gallery
// follows above. Called once from init(); language switches reload the
// page onto the other static document (see setLanguage()), so there's
// no separate re-render path to keep in sync here.
function renderEvents() {
  const resolved = resolveUpcomingEvents(rawEvents).map((entry) => ({
    ...entry,
    event: {
      ...entry.event,
      title: pickLang(entry.event.title),
      description: pickLang(entry.event.description),
      tag: pickLang(entry.event.tag),
      price: pickLang(entry.event.price),
    },
  }));

  if (resolved.length === 0) {
    document.getElementById("events").hidden = true;
    document.querySelectorAll('[data-section="events"]').forEach((el) => (el.hidden = true));
    return;
  }

  renderEventsSection(document.getElementById("events-grid"), resolved, {
    upNext: t("events.upNext"),
    tonight: t("events.tonight"),
    weekdayShort: i18n[currentLanguage].events.weekdayShort,
  });
}

// Looks up a dot-path in the active language's dict, falling back to
// English if that key is missing there too. An optional `vars` object
// fills in `{name}` placeholders a string may contain (gallery.json's
// per-photo counter/alt-text strings, mainly) — every other call site
// just omits it and gets the plain string back untouched.
function t(path, vars) {
  const str = resolveKey(i18n[currentLanguage], path) ?? resolveKey(i18n.en, path) ?? path;
  if (!vars) return str;
  return Object.entries(vars).reduce((s, [key, value]) => s.replaceAll(`{${key}}`, value), str);
}

function resolveKey(dict, path) {
  return path.split(".").reduce((node, key) => (node && typeof node === "object" ? node[key] : undefined), dict);
}

// Resolves a menu.json field that may be a plain string (price, tag, name)
// or a { en, fi } object (description) into the active language's text.
function pickLang(field) {
  if (field && typeof field === "object") return field[currentLanguage] || field.en || "";
  return field;
}

// Single pass over every element tagged data-i18n="some.path" (textContent),
// data-i18n-placeholder="some.path" (the placeholder attribute, for form
// inputs), data-i18n-aria-label="some.path" (the aria-label attribute,
// for icon-only controls like the FAB), or data-i18n-alt="some.path" (the
// alt attribute, for the hero photo's <img> — see "Hero photo") — covers
// static markup in index.html plus the hooks nav.js, footer.js, button.js,
// eventModal.js and fab.js leave on the elements they render.
function applyTranslations() {
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });
}

// ---------- mobile topbar ----------

// Hides the mobile topbar when the visitor scrolls down past it, and brings
// it back as soon as they scroll up — a small threshold avoids it flickering
// on the sub-pixel scroll jitter some trackpads/phones report.
//
// mobileNav.js's link clicks set document.body.dataset.navJump = "true"
// for the duration of their own scrollIntoView() jump — without that, this
// handler sees the jump's own downward motion as "the visitor scrolled
// down" and hides the topbar mid-jump, right when the visitor just tapped
// a link specifically to land next to it (leaving the scroll-margin-top
// clearance reserved for it looking like unexplained empty space instead).
function initMobileTopbarAutoHide() {
  const topbar = document.getElementById("mobile-topbar");
  if (!topbar) return;

  const SCROLL_THRESHOLD = 8;
  let lastScrollY = window.scrollY;

  window.addEventListener(
    "scroll",
    () => {
      const currentScrollY = window.scrollY;
      if (document.body.dataset.navJump === "true") {
        lastScrollY = currentScrollY;
        return;
      }

      const delta = currentScrollY - lastScrollY;
      if (Math.abs(delta) < SCROLL_THRESHOLD) return;

      const scrollingDown = delta > 0;
      topbar.classList.toggle("topbar--hidden", scrollingDown && currentScrollY > topbar.offsetHeight);
      lastScrollY = currentScrollY;
    },
    { passive: true }
  );
}

// ---------- stale theme cleanup ----------

// The removed theme toggle used to persist its choice under this key —
// clearing it here means a returning visitor who had picked "light"
// doesn't carry that choice around forever in localStorage for no
// reason now that there's nothing left to apply it to.
function forgetStaleTheme() {
  try {
    localStorage.removeItem("klandestina-theme");
  } catch (e) {
    /* ignore — nothing to clean up if storage isn't available */
  }
}

